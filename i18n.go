package gotsk

import (
	"fmt"
	"net/http"
	"strings"
)

const (
	langPT     = "pt-BR"
	langEN     = "en"
	langCookie = "gotsk_lang"
)

// translator devolve o texto de uma chave no idioma da requisição. Com
// argumentos, o texto é tratado como formato (fmt.Sprintf).
type translator func(key string, args ...any) string

func supportedLang(l string) bool { return l == langPT || l == langEN }

// langFromRequest escolhe o idioma: cookie explícito, depois Accept-Language,
// e por último pt-BR.
func langFromRequest(r *http.Request) string {
	if c, err := r.Cookie(langCookie); err == nil && supportedLang(c.Value) {
		return c.Value
	}
	if strings.HasPrefix(strings.ToLower(r.Header.Get("Accept-Language")), "en") {
		return langEN
	}
	return langPT
}

func newTranslator(lang string) translator {
	return func(key string, args ...any) string {
		s, ok := messages[lang][key]
		if !ok {
			s, ok = messages[langPT][key]
		}
		if !ok {
			return key
		}
		if len(args) > 0 {
			return fmt.Sprintf(s, args...)
		}
		return s
	}
}

